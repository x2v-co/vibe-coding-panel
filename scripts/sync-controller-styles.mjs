// Generate the standalone controller stylesheet from the same source as Panel.
// Do not hand-edit generated controller.css: update src/styles.css or the adapters.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const source = await read('src/styles.css');
const section = (start, end) => {
  const from = source.indexOf(start), to = source.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error(`Panel CSS section missing: ${start}`);
  return source.slice(from, to);
};
const appearance = [
  '.shell:not(.is-desktop),body:has(.shell:not(.is-desktop)) {\n' + [...section(':root {', '* { box-sizing').matchAll(/  --[^;]+;/g)].map(x=>x[0]).join('\n') + '\n}',
  section(".app-shell[data-theme='smoke']", '.topbar {').replace(/\.app-shell(\[data-theme='[^']+'\])/g, '.shell:not(.is-desktop)$1,body:has(.shell:not(.is-desktop)$1)'),
  section('.device {', '.knob {'),
  section('\n.display-bezel {', '\n.display-main {'),
  section('.control-bank {', '.device-footer {'),
  section('.layout-options {', '.theme-options {'),
  section('/* Reference hardware:', '@media (max-width: 800px)'),
].join('\n');
// .display is also used by the desktop hub. Scope the original screen to its bezel.
const scoped = appearance.replace(/(^|\n)\.display \{/g, '$1.display-bezel .display {');
await writeFile(new URL('public/controller.css', root),
  '/* Generated by scripts/sync-controller-styles.mjs from src/styles.css. */\n' +
  source.slice(0, source.indexOf('\n')) + '\n' +
  await read('public/controller-desktop.css') + '\n' + scoped + '\n' +
  await read('public/controller-mobile.css'));

execFileSync(process.execPath, [fileURLToPath(new URL('node_modules/typescript/bin/tsc', root)), '-p', fileURLToPath(new URL('tsconfig.controller.json', root))], {stdio:'inherit'});
